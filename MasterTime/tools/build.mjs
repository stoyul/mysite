// Small dependency-free packager for this project's explicit module graph.
// Source modules remain authoritative; generated bundle also opens via file://.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
const root=new URL('../',import.meta.url);
const ordered=['data/game-scenarios.mjs','src/domain.mjs','src/game.mjs','src/game-view.mjs','src/journey-view.mjs','src/chapters.mjs','src/chapter-view.mjs','src/passport.mjs','src/passport-view.mjs','src/app.mjs'];
const catalog=await readFile(new URL('data/cards.json',root),'utf8');
let output='/* Generated by tools/build.mjs. Edit source modules, then rebuild. */\n(()=>{\n"use strict";\nconst __modules={};\nconst __catalog='+catalog+';\n';
for(const file of ordered){
  let source=await readFile(new URL(file,root),'utf8');
  const names=[...source.matchAll(/export\s+(?:function|const|let)\s+(\w+)/g)].map(m=>m[1]);
  let hasDefault=false;
  source=source.replace(/import\s+(\{[^}]+\}|\w+)\s+from\s+['"]([^'"]+)['"];?/g,(_,binding,relative)=>{
    const resolved=path.posix.normalize(path.posix.join(path.posix.dirname(file),relative));
    if(!ordered.includes(resolved)||ordered.indexOf(resolved)>=ordered.indexOf(file))throw Error('Unsupported dependency order: '+relative);
    return `const ${binding}=__modules[${JSON.stringify(resolved)}]${binding.startsWith('{')?'':'.default'};`;
  });
  source=source.replace(/export default /g,()=>{hasDefault=true;return 'const __default=';}).replace(/\bexport (?=function|const|let)/g,'');
  if(file==='src/app.mjs'){
    const start=source.indexOf("try{const response=await fetch('./data/cards.json')"),end=source.indexOf('// Close existing past months',start);
    if(start<0||end<0)throw Error('Catalog bootstrap changed: update packager');
    source=source.slice(0,start)+'cards=__catalog;\n'+source.slice(end);
  }
  if(/^\s*(import|export)\s/m.test(source))throw Error('Unsupported module syntax: '+file);
  output+=`__modules[${JSON.stringify(file)}]=(()=>{\n${source}\nreturn {${names.join(',')}${hasDefault?(names.length?',':'')+'default:__default':''}};\n})();\n`;
}
output+='})();\n';
await mkdir(new URL('assets/',root),{recursive:true});
await writeFile(new URL('assets/app.js',root),output);
await writeFile(new URL('assets/app-20261015.js',root),output);
await writeFile(new URL('assets/app-20261015-cards.js',root),output);
await writeFile(new URL('assets/styles-20261015.css',root),await readFile(new URL('src/styles.css',root),'utf8'));
await writeFile(new URL('assets/styles-20261015-cards.css',root),await readFile(new URL('src/styles.css',root),'utf8'));
console.log(`Built assets/app.js from ${ordered.length} source modules and the 74-card catalog.`);
