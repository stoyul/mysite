  var LANGS = { ru: 1, en: 1, de: 1 };
  var STORE = "ys_lang"; // общий ключ со всем сайтом yuliastoyanova.com

  function get(lang, key) {
    var d = DICT[lang] || DICT.ru;
    return (key in d) ? d[key] : DICT.ru[key];
  }

  function apply(lang) {
    if (!LANGS[lang]) lang = "ru";
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var v = get(lang, el.getAttribute("data-i18n"));
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(function (el) {
      var v = get(lang, el.getAttribute("data-i18n-ph"));
      if (v != null) el.setAttribute("placeholder", v.replace(/<[^>]*>/g, ""));
    });

    var t = get(lang, "_title"); if (t) document.title = t;
    var m = document.querySelector('meta[name="description"]');
    var d = get(lang, "_desc"); if (m && d) m.setAttribute("content", d);

    document.querySelectorAll(".lang button").forEach(function (b) {
      b.classList.toggle("active", b.getAttribute("data-lang") === lang);
    });

    try { localStorage.setItem(STORE, lang); } catch (e) {}
  }

  function init() {
    var lang = "ru";
    try {
      var qp = new URLSearchParams(location.search).get("lang");
      if (qp && LANGS[qp]) lang = qp;
      else { var s = localStorage.getItem(STORE); if (s && LANGS[s]) lang = s; }
    } catch (e) {}
    document.querySelectorAll(".lang button").forEach(function (b) {
      b.addEventListener("click", function () { apply(b.getAttribute("data-lang")); });
    });
    apply(lang);
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
